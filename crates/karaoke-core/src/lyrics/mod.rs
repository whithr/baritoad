#[cfg(test)]
mod tests {
    use super::*;

    fn displays(c: &CleanLyrics) -> Vec<&str> {
        c.lines.iter().map(|l| l.display.as_str()).collect()
    }

    // -- headers --

    #[test]
    fn bracket_header_variants_are_stripped() {
        for h in [
            "[Chorus]",
            "[Verse 2]",
            "[Bridge: Fictional Artist]",
            "[Verse 2: Someone & Someone Else]",
            "(Chorus)",
            "{Hook}",
            "[PRE-CHORUS]",
            "[Pre-Chorus 2]",
            "[Part II]",
        ] {
            let c = clean(&format!("{h}\nmoonlight on the water\n"));
            assert_eq!(displays(&c), vec!["moonlight on the water"], "header {h}");
            assert!(
                matches!(c.edits[0], Edit::SectionHeaderRemoved { line: 1, .. }),
                "header {h} -> {:?}",
                c.edits
            );
        }
    }

    #[test]
    fn bare_colon_header_is_stripped() {
        let c = clean("Chorus:\nsailing home again\n");
        assert_eq!(displays(&c), vec!["sailing home again"]);
        assert_eq!(c.edits.len(), 1);
    }

    #[test]
    fn bare_keyword_without_colon_is_kept() {
        // could be a lyric word — conservative rule requires the colon
        let c = clean("Chorus\nsailing home again\n");
        assert_eq!(displays(&c), vec!["Chorus", "sailing home again"]);
        assert!(c.edits.is_empty());
    }

    #[test]
    fn non_header_bracket_line_is_kept() {
        let c = clean("[?]\nmystery line\n");
        assert_eq!(displays(&c), vec!["[?]", "mystery line"]);
    }

    // -- repeat markers --

    #[test]
    fn trailing_line_markers_expand() {
        for m in ["(x2)", "(2x)", "[x2]", "x2", "X2", "\u{d7}2", "(\u{d7}2)"] {
            let c = clean(&format!("row the boat ashore {m}\n"));
            assert_eq!(
                displays(&c),
                vec!["row the boat ashore", "row the boat ashore"],
                "marker {m}"
            );
            assert!(c.lines[1].repeated && !c.lines[0].repeated);
            assert_eq!(c.lines[1].source_line, 1); // provenance
            assert!(matches!(
                c.edits[0],
                Edit::RepeatExpanded {
                    times: 2,
                    scope: RepeatScope::Line,
                    ..
                }
            ));
        }
    }

    #[test]
    fn x3_repeats_three_times_and_x99_is_clamped() {
        let c = clean("hey now [x3]\n");
        assert_eq!(c.lines.len(), 3);
        let c = clean("hey now (x99)\n");
        assert_eq!(c.lines.len(), MAX_REPEAT as usize);
    }

    #[test]
    fn lone_marker_line_repeats_the_stanza() {
        let c = clean("first light\nsecond sight\nx2\n\nnext stanza\n");
        assert_eq!(
            displays(&c),
            vec![
                "first light",
                "second sight",
                "first light",
                "second sight",
                "next stanza"
            ]
        );
        assert!(matches!(
            c.edits[0],
            Edit::RepeatExpanded {
                line: 3,
                scope: RepeatScope::Stanza,
                lines_added: 2,
                ..
            }
        ));
    }

    #[test]
    fn header_marker_repeats_the_section() {
        let c = clean("[Chorus x2]\ngolden hour\nfading now\n\n[Verse 3]\nonward\n");
        assert_eq!(
            displays(&c),
            vec![
                "golden hour",
                "fading now",
                "golden hour",
                "fading now",
                "onward"
            ]
        );
        let rep = c
            .edits
            .iter()
            .find(|e| matches!(e, Edit::RepeatExpanded { .. }))
            .unwrap();
        match rep {
            Edit::RepeatExpanded {
                scope, section, ..
            } => {
                assert_eq!(*scope, RepeatScope::Section);
                assert_eq!(section.as_deref(), Some("chorus"));
            }
            _ => unreachable!(),
        }
        assert!(c.summary().contains("expanded one x2 chorus"), "{}", c.summary());
    }

    #[test]
    fn header_with_marker_outside_brackets() {
        let c = clean("[Chorus] (x2)\nla la line\n");
        assert_eq!(displays(&c), vec!["la la line", "la la line"]);
    }

    #[test]
    fn section_repeat_ends_at_next_header() {
        let c = clean("[Chorus x2]\nchorus line\n[Outro]\nlast words\n");
        assert_eq!(
            displays(&c),
            vec!["chorus line", "chorus line", "last words"]
        );
    }

    #[test]
    fn line_repeat_nested_in_repeated_section() {
        // the x2 line expands first, then the section copy duplicates the
        // already-expanded body
        let c = clean("[Chorus x2]\necho me (x2)\nsolid ground\n");
        assert_eq!(
            displays(&c),
            vec![
                "echo me",
                "echo me",
                "solid ground",
                "echo me",
                "echo me",
                "solid ground"
            ]
        );
        assert_eq!(
            c.edits
                .iter()
                .filter(|e| matches!(e, Edit::RepeatExpanded { .. }))
                .count(),
            2
        );
    }

    #[test]
    fn ordinary_words_ending_in_x_are_not_markers() {
        let c = clean("in a box\nfeeling lax\n");
        assert!(c.edits.is_empty());
        assert_eq!(c.lines.len(), 2);
    }

    // -- ad-libs --

    #[test]
    fn inline_adlib_is_flagged_and_kept_verbatim() {
        let c = clean("driving all night (oh yeah) to see you\n");
        assert_eq!(displays(&c), vec!["driving all night (oh yeah) to see you"]);
        let flags: Vec<bool> = c.lines[0].words.iter().map(|w| w.ad_lib).collect();
        assert_eq!(
            flags,
            vec![false, false, false, true, true, false, false, false]
        );
        assert!(matches!(&c.edits[0], Edit::AdLibFlagged { line: 1, text } if text == "(oh yeah)"));
    }

    #[test]
    fn whole_line_parenthetical_is_adlib_not_header() {
        let c = clean("(woo)\nreal line\n");
        assert_eq!(displays(&c), vec!["(woo)", "real line"]);
        assert!(c.lines[0].words[0].ad_lib);
        assert!(matches!(c.edits[0], Edit::AdLibFlagged { .. }));
    }

    #[test]
    fn adlib_and_trailing_repeat_coexist() {
        let c = clean("shine on (shine on) x2\n");
        assert_eq!(displays(&c), vec!["shine on (shine on)", "shine on (shine on)"]);
        assert!(c.lines[0].words[2].ad_lib && c.lines[0].words[3].ad_lib);
    }

    // -- credit / boilerplate lines --

    #[test]
    fn credit_lines_are_stripped() {
        for l in [
            "Produced by Fictional Producer",
            "Lyrics by A. Nobody",
            "Written by Someone",
            "\u{a9} 2026 Made-Up Records",
            "(c) 2026 Made-Up Records",
            "All rights reserved. International copyright secured.",
            "Lyrics licensed and provided by ExampleFind",
            "You might also like",
            "23 ContributorsMade-Up Song Lyrics",
            "Embed",
        ] {
            let c = clean(&format!("{l}\nkept lyric line\n"));
            assert_eq!(displays(&c), vec!["kept lyric line"], "credit {l}");
            assert!(
                matches!(c.edits[0], Edit::CreditLineRemoved { line: 1, .. }),
                "credit {l} -> {:?}",
                c.edits
            );
        }
    }

    #[test]
    fn embed_suffix_on_last_line_is_stripped() {
        let c = clean("first line\nand then I'm gone42Embed");
        assert_eq!(displays(&c), vec!["first line", "and then I'm gone"]);
        assert!(matches!(&c.edits[0], Edit::EmbedSuffixRemoved { line: 2, text } if text == "42Embed"));
    }

    #[test]
    fn lyric_mentioning_produced_mid_sentence_is_kept() {
        let c = clean("we produced by hand a little dream\n");
        assert_eq!(c.lines.len(), 1);
        assert!(c.edits.is_empty());
    }

    // -- unicode --

    #[test]
    fn smart_quotes_and_unicode_punct_survive_verbatim() {
        let text = "don\u{2019}t say \u{201c}goodbye\u{201d} \u{2014} stay\n";
        let c = clean(text);
        assert_eq!(c.to_text(), text);
        assert_eq!(c.lines[0].words[0].display, "don\u{2019}t");
    }

    // -- passthrough & reconstruction --

    #[test]
    fn clean_file_passes_through_byte_identical() {
        let text = "over the hills we wander\nthrough the pines we roam\n\nevery star a lantern\nleading us back home\n";
        let c = clean(text);
        assert!(c.edits.is_empty());
        assert_eq!(c.to_text(), text);
        assert_eq!(c.lines[2].blank_before, 1); // stanza break preserved
    }

    #[test]
    fn crlf_input_is_tolerated() {
        let c = clean("[Chorus]\r\nline one\r\nline two\r\n");
        assert_eq!(displays(&c), vec!["line one", "line two"]);
    }

    #[test]
    fn no_trailing_newline_is_preserved() {
        let text = "line one\nline two";
        assert_eq!(clean(text).to_text(), text);
    }

    // -- summary & structure --

    #[test]
    fn summary_counts_read_naturally() {
        let c = clean(
            "[Verse 1]\nfirst line\n\n[Chorus]\nsecond line (x2)\n\n[Outro]\n(hey)\nProduced by Nobody\n",
        );
        let s = c.summary();
        assert!(s.contains("removed 3 section headers"), "{s}");
        assert!(s.contains("removed 1 credit/boilerplate line"), "{s}");
        assert!(s.contains("expanded one x2 line"), "{s}");
        assert!(s.contains("flagged 1 ad-lib"), "{s}");
    }

    #[test]
    fn summary_no_changes() {
        assert_eq!(clean("plain line\n").summary(), "no changes needed");
    }

    #[test]
    fn lyric_words_flatten_with_anchor_norms() {
        let c = clean("Don\u{2019}t stop (woo)\n");
        let w = c.lyric_words();
        assert_eq!(w.len(), 3);
        assert_eq!(w[0].display, "Don\u{2019}t");
        assert_eq!(w[0].norm, "DON'T"); // anchor.rs folding, not duplicated here
    }

    #[test]
    fn edit_display_renders_line_references() {
        let c = clean("[Chorus]\nhello\n");
        let rendered = format!("{}", c.edits[0]);
        assert!(rendered.contains("line 1"), "{rendered}");
    }
}
