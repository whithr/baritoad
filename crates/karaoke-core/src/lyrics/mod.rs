/// An open section (a header carrying a repeat count was seen; the section
/// runs until a blank line, the next header, or EOF, then gets duplicated).
struct OpenSection {
    name: String,
    times: u32,
    marker: String,
    header_line: usize,
    out_start: usize,
}

/// Run the cleanup pass. Never fails: unrecognized content is kept verbatim
/// (cleanup must not eat lyrics), and every change lands in `edits`.
pub fn clean(text: &str) -> CleanLyrics {
    let trailing_newline = text.ends_with('\n');
    let mut src: Vec<&str> = text.split('\n').collect();
    if trailing_newline {
        src.pop(); // the empty element after the final '\n'
    }
    let last_content_line = src
        .iter()
        .rposition(|l| !l.trim().is_empty())
        .unwrap_or(usize::MAX);

    let mut lines: Vec<CleanLine> = Vec::new();
    let mut edits: Vec<Edit> = Vec::new();
    let mut pending_blanks = 0usize;
    let mut stanza_start = 0usize; // output index where the current stanza began
    let mut section: Option<OpenSection> = None;

    let close_section = |section: &mut Option<OpenSection>,
                         lines: &mut Vec<CleanLine>,
                         edits: &mut Vec<Edit>| {
        if let Some(sec) = section.take() {
            let body: Vec<CleanLine> = lines[sec.out_start..].to_vec();
            if body.is_empty() || sec.times < 2 {
                return;
            }
            let mut added = 0usize;
            for _ in 1..sec.times {
                for (i, l) in body.iter().enumerate() {
                    let mut c = l.clone();
                    c.repeated = true;
                    c.blank_before = if i == 0 { 1 } else { 0 }; // each copy is a stanza
                    lines.push(c);
                    added += 1;
                }
            }
            edits.push(Edit::RepeatExpanded {
                line: sec.header_line,
                marker: sec.marker,
                times: sec.times,
                scope: RepeatScope::Section,
                section: Some(sec.name),
                lines_added: added,
            });
        }
    };

    for (idx, raw) in src.iter().enumerate() {
        let n = idx + 1; // 1-based source line number
        let line = raw.strip_suffix('\r').unwrap_or(raw);
        let trimmed = line.trim();

        // blank: stanza / section boundary
        if trimmed.is_empty() {
            close_section(&mut section, &mut lines, &mut edits);
            pending_blanks += 1;
            stanza_start = lines.len();
            continue;
        }

        // section header?
        if let Some((name, times)) = parse_header_line(line) {
            close_section(&mut section, &mut lines, &mut edits);
            edits.push(Edit::SectionHeaderRemoved {
                line: n,
                text: trimmed.to_string(),
            });
            if times >= 2 {
                section = Some(OpenSection {
                    name,
                    times,
                    marker: trimmed.to_string(),
                    header_line: n,
                    out_start: lines.len(),
                });
            }
            stanza_start = lines.len();
            continue;
        }

        // lone repeat marker line -> duplicate the stanza above it
        if let Some(times) = parse_repeat_marker(trimmed) {
            let body: Vec<CleanLine> = lines[stanza_start..].to_vec();
            let mut added = 0usize;
            for _ in 1..times {
                for l in &body {
                    let mut c = l.clone();
                    c.repeated = true;
                    c.blank_before = 0; // flows on within the stanza
                    lines.push(c);
                    added += 1;
                }
            }
            edits.push(Edit::RepeatExpanded {
                line: n,
                marker: trimmed.to_string(),
                times,
                scope: RepeatScope::Stanza,
                section: None,
                lines_added: added,
            });
            continue;
        }

        // credit / boilerplate line
        if is_credit_line(line) {
            edits.push(Edit::CreditLineRemoved {
                line: n,
                text: trimmed.to_string(),
            });
            continue;
        }

        // --- a kept lyric line ---
        let mut display = line.to_string();

        // Genius embed suffix glued to the last content line ("…gone42Embed")
        if idx == last_content_line && display.trim_end().ends_with("Embed") {
            let t = display.trim_end();
            let without = t.strip_suffix("Embed").unwrap_or(t);
            let without = without.trim_end_matches(|c: char| c.is_ascii_digit());
            let removed = t[without.len()..].to_string();
            edits.push(Edit::EmbedSuffixRemoved {
                line: n,
                text: removed,
            });
            display = without.to_string();
            if display.trim().is_empty() {
                continue; // the whole line was junk
            }
        }

        // trailing repeat marker -> the line repeats
        let mut line_times = 1u32;
        let mut line_marker = String::new();
        if let Some((rest, times, marker)) = split_trailing_repeat(&display) {
            if !rest.trim().is_empty() {
                display = rest;
                line_times = times;
                line_marker = marker;
            }
        }

        // parenthetical ad-libs: flag, keep verbatim
        let ranges = parenthetical_ranges(&display);
        for &(s, e) in &ranges {
            edits.push(Edit::AdLibFlagged {
                line: n,
                text: display[s..e].to_string(),
            });
        }
        let words: Vec<CleanWord> = tokens_with_spans(&display)
            .into_iter()
            .map(|(s, e)| CleanWord {
                display: display[s..e].to_string(),
                ad_lib: ranges.iter().any(|&(rs, re)| s < re && e > rs),
            })
            .collect();

        let clean_line = CleanLine {
            display,
            words,
            source_line: n,
            blank_before: std::mem::take(&mut pending_blanks),
            repeated: false,
        };
        lines.push(clean_line);
        if line_times >= 2 {
            let template = lines.last().expect("just pushed").clone();
            let mut added = 0usize;
            for _ in 1..line_times {
                let mut c = template.clone();
                c.repeated = true;
                c.blank_before = 0;
                lines.push(c);
                added += 1;
            }
            edits.push(Edit::RepeatExpanded {
                line: n,
                marker: line_marker,
                times: line_times,
                scope: RepeatScope::Line,
                section: None,
                lines_added: added,
            });
        }
    }
    close_section(&mut section, &mut lines, &mut edits);

    CleanLyrics {
        lines,
        edits,
        trailing_newline,
    }
}

