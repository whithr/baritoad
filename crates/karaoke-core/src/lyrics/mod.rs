//! Lyric cleanup pass (PLAN.md §3): pasted lyrics arrive dirty — Genius /
//! AZLyrics style section headers, "(x2)" repeat markers, parenthetical
//! ad-libs, credit lines. This stage runs **before** alignment and decides
//! *what words exist*; the alignment normalization ([`crate::alignment::anchor`])
//! decides *how they are matched*. Charset folding is deliberately not
//! duplicated here.
//!
//! Rules (PLAN.md §3, §4):
//! - section headers (`[Chorus]`, `[Verse 2]`, `[Bridge: Artist]`, `(Chorus)`,
//!   bare `Chorus:` lines) are **stripped**
//! - repeat markers (`(x2)`, `x2`, `(2x)`, `[x3]`, `×2`) are **expanded** —
//!   on a line, on a stanza (lone marker line), or on a section (marker in a
//!   header) — with provenance kept on the generated lines
//! - parenthetical ad-libs (`(oh yeah)`) are **flagged, kept** — alignment may
//!   place them, display can style them differently
//! - credit / boilerplate lines ("Produced by …", "© …", Genius embed junk)
//!   are **stripped**
//! - everything kept preserves its display text **verbatim**; a clean input
//!   reconstructs byte-identical via [`CleanLyrics::to_text`]
//!
//! Every change is recorded in [`CleanLyrics::edits`] with source-line
//! references, and [`CleanLyrics::summary`] renders the one-line human form
//! ("removed 4 section headers, expanded one x2 chorus" — PLAN.md §4). The
//! default requires no decisions.

use serde::Serialize;

use crate::alignment::anchor;
use crate::error::{Error, Result};
use crate::timing::WordTimingMap;

/// Repeat counts are clamped here — "(x99)" in pasted junk must not explode
/// the song.
pub const MAX_REPEAT: u32 = 8;

/// Section-header keywords (lowercase). A bracketed or `Keyword:` line whose
/// spec starts with one of these is a header, optionally followed by a number
/// ("Verse 2"), an artist ("Bridge: Artist"), and/or a repeat marker
/// ("Chorus x2").
const SECTION_KEYWORDS: &[&str] = &[
    "intro",
    "verse",
    "chorus",
    "pre-chorus",
    "prechorus",
    "post-chorus",
    "postchorus",
    "hook",
    "bridge",
    "refrain",
    "outro",
    "interlude",
    "instrumental",
    "solo",
    "break",
    "breakdown",
    "drop",
    "part",
];

/// One kept word. Display text is verbatim (including any parentheses).
#[derive(Debug, Clone, Serialize)]
pub struct CleanWord {
    pub display: String,
    /// Parenthetical ad-lib — alignment may place it, display may style it.
    pub ad_lib: bool,
}

/// One kept lyric line. Lines matter downstream: LRC/ASS/UltraStar exporters
/// are line-oriented.
#[derive(Debug, Clone, Serialize)]
pub struct CleanLine {
    /// Verbatim kept text (only removed markers/suffixes are gone).
    pub display: String,
    pub words: Vec<CleanWord>,
    /// 1-based line number in the pasted input this line came from.
    pub source_line: usize,
    /// Blank lines between the previous kept line and this one (stanza
    /// structure, preserved for reconstruction and exporters).
    pub blank_before: usize,
    /// True when this line was generated by repeat expansion (provenance:
    /// `source_line` then points at the line it is a copy of).
    pub repeated: bool,
}

/// What a repeat marker applied to.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum RepeatScope {
    /// Marker trailing a lyric line — that line repeats.
    Line,
    /// Lone marker line — the stanza above it repeats.
    Stanza,
    /// Marker inside a section header — the section below repeats.
    Section,
}

/// One recorded edit, with a source-line reference. Machine-readable change
/// summary (PLAN.md §4).
#[derive(Debug, Clone, Serialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum Edit {
    SectionHeaderRemoved {
        line: usize,
        text: String,
    },
    CreditLineRemoved {
        line: usize,
        text: String,
    },
    /// Genius paste junk glued to the last line ("…goodbye42Embed").
    EmbedSuffixRemoved {
        line: usize,
        text: String,
    },
    RepeatExpanded {
        /// Source line the marker sat on.
        line: usize,
        /// The marker exactly as pasted (e.g. "(x2)").
        marker: String,
        times: u32,
        scope: RepeatScope,
        /// Section name when the marker was in a header (e.g. "chorus").
        section: Option<String>,
        /// Lines added to the output by this expansion.
        lines_added: usize,
    },
    AdLibFlagged {
        line: usize,
        text: String,
    },
}

impl std::fmt::Display for Edit {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Edit::SectionHeaderRemoved { line, text } => {
                write!(f, "line {line}: removed section header \"{text}\"")
            }
            Edit::CreditLineRemoved { line, text } => {
                write!(f, "line {line}: removed credit/boilerplate \"{text}\"")
            }
            Edit::EmbedSuffixRemoved { line, text } => {
                write!(f, "line {line}: removed embed tag \"{text}\"")
            }
            Edit::RepeatExpanded {
                line,
                marker,
                times,
                scope,
                section,
                lines_added,
            } => {
                let what = match (scope, section) {
                    (RepeatScope::Section, Some(name)) => name.clone(),
                    (RepeatScope::Section, None) => "section".into(),
                    (RepeatScope::Stanza, _) => "stanza".into(),
                    (RepeatScope::Line, _) => "line".into(),
                };
                write!(
                    f,
                    "line {line}: expanded {marker} — {what} x{times} (+{lines_added} line(s))"
                )
            }
            Edit::AdLibFlagged { line, text } => {
                write!(f, "line {line}: flagged ad-lib \"{text}\" (kept)")
            }
        }
    }
}

/// Cleanup output: kept line/word structure + the edit log.
#[derive(Debug, Clone, Serialize)]
pub struct CleanLyrics {
    pub lines: Vec<CleanLine>,
    pub edits: Vec<Edit>,
    #[serde(skip)]
    trailing_newline: bool,
}

impl CleanLyrics {
    /// Reconstruct the cleaned text. When the input needed no edits this is
    /// byte-identical to the input (CRLF inputs come back LF — the one
    /// normalization applied unconditionally).
    pub fn to_text(&self) -> String {
        let mut out = String::new();
        for (i, line) in self.lines.iter().enumerate() {
            if i > 0 {
                out.push('\n');
            }
            for _ in 0..line.blank_before {
                out.push('\n');
            }
            out.push_str(&line.display);
        }
        if self.trailing_newline && !self.lines.is_empty() {
            out.push('\n');
        }
        out
    }

    pub fn word_count(&self) -> usize {
        self.lines.iter().map(|l| l.words.len()).sum()
    }

    /// Flatten to the aligner's input words. Norms come from
    /// [`anchor::normalize_word`] — cleanup never duplicates that folding.
    pub fn lyric_words(&self) -> Vec<anchor::LyricWord> {
        self.lines
            .iter()
            .flat_map(|l| l.words.iter())
            .map(|w| anchor::LyricWord {
                display: w.display.clone(),
                norm: anchor::normalize_word(&w.display),
            })
            .collect()
    }

    /// Stamp lyric line/word indices and ad-lib flags onto a timing map whose
    /// words came 1:1 from [`Self::lyric_words`]. This is the stable link
    /// between the timing map and the lyric structure (exporters are
    /// line-oriented).
    pub fn annotate_map(&self, map: &mut WordTimingMap) -> Result<()> {
        if self.word_count() != map.words.len() {
            return Err(Error::InvalidInput(format!(
                "timing map has {} words but cleaned lyrics have {} — map was not built from these lyrics",
                map.words.len(),
                self.word_count()
            )));
        }
        let mut k = 0usize;
        for (li, line) in self.lines.iter().enumerate() {
            for (wi, w) in line.words.iter().enumerate() {
                map.words[k].line = Some(li);
                map.words[k].word_in_line = Some(wi);
                map.words[k].ad_lib = w.ad_lib;
                k += 1;
            }
        }
        Ok(())
    }

    /// One-line human rendering of the edit log (PLAN.md §4:
    /// "removed 4 section headers, expanded one x2 chorus").
    pub fn summary(&self) -> String {
        let mut headers = 0usize;
        let mut credits = 0usize;
        let mut adlibs = 0usize;
        let mut repeats: Vec<(&u32, &RepeatScope, &Option<String>)> = Vec::new();
        for e in &self.edits {
            match e {
                Edit::SectionHeaderRemoved { .. } => headers += 1,
                Edit::CreditLineRemoved { .. } | Edit::EmbedSuffixRemoved { .. } => credits += 1,
                Edit::AdLibFlagged { .. } => adlibs += 1,
                Edit::RepeatExpanded {
                    times,
                    scope,
                    section,
                    ..
                } => repeats.push((times, scope, section)),
            }
        }
        let mut parts: Vec<String> = Vec::new();
        if headers > 0 {
            parts.push(format!(
                "removed {headers} section header{}",
                plural(headers)
            ));
        }
        if credits > 0 {
            parts.push(format!(
                "removed {credits} credit/boilerplate line{}",
                plural(credits)
            ));
        }
        match repeats.len() {
            0 => {}
            1 => {
                let (times, scope, section) = repeats[0];
                let what = match (scope, section) {
                    (RepeatScope::Section, Some(name)) => name.clone(),
                    (RepeatScope::Section, None) => "section".into(),
                    (RepeatScope::Stanza, _) => "stanza".into(),
                    (RepeatScope::Line, _) => "line".into(),
                };
                parts.push(format!("expanded one x{times} {what}"));
            }
            n => parts.push(format!("expanded {n} marked repeats")),
        }
        if adlibs > 0 {
            parts.push(format!("flagged {adlibs} ad-lib{}", plural(adlibs)));
        }
        if parts.is_empty() {
            "no changes needed".into()
        } else {
            parts.join(", ")
        }
    }
}

fn plural(n: usize) -> &'static str {
    if n == 1 {
        ""
    } else {
        "s"
    }
}

// ---------------------------------------------------------------------------
// token-level helpers (hand parsing, std only — no regex dependency)
// ---------------------------------------------------------------------------

/// "x2" / "2x" / "×3" / "3×" (case-insensitive), count clamped to
/// [`MAX_REPEAT`]. Counts below 2 are not markers.
fn parse_repeat_token(s: &str) -> Option<u32> {
    let s = s.trim();
    let n: u32 = if let Some(digits) = s
        .strip_prefix(['x', 'X'])
        .or_else(|| s.strip_prefix('\u{d7}'))
    {
        digits.parse().ok()?
    } else if let Some(digits) = s
        .strip_suffix(['x', 'X'])
        .or_else(|| s.strip_suffix('\u{d7}'))
    {
        digits.parse().ok()?
    } else {
        return None;
    };
    if (2..=99).contains(&n) {
        Some(n.min(MAX_REPEAT))
    } else {
        None
    }
}

/// A repeat marker possibly wrapped in one pair of `()` or `[]`.
fn parse_repeat_marker(s: &str) -> Option<u32> {
    let s = s.trim();
    let inner = strip_enclosing(s).map(|(_, i)| i).unwrap_or(s);
    parse_repeat_token(inner)
}

/// When `s` is fully enclosed in one balanced `[..]`, `(..)` or `{..}` pair,
/// return the bracket kind and inner text.
fn strip_enclosing(s: &str) -> Option<(char, &str)> {
    let s = s.trim();
    let open = s.chars().next()?;
    let close = match open {
        '[' => ']',
        '(' => ')',
        '{' => '}',
        _ => return None,
    };
    let (end, _) = matching_close(s, open, close)?;
    if end != s.len() - close.len_utf8() {
        return None; // closes before the end: not fully enclosed
    }
    Some((open, &s[open.len_utf8()..end]))
}

/// Byte index of the close bracket matching the open bracket at byte 0.
fn matching_close(s: &str, open: char, close: char) -> Option<(usize, usize)> {
    let mut depth = 0i32;
    for (i, c) in s.char_indices() {
        if c == open {
            depth += 1;
        } else if c == close {
            depth -= 1;
            if depth == 0 {
                return Some((i, i + close.len_utf8()));
            }
        }
    }
    None
}

fn is_number_token(t: &str) -> bool {
    !t.is_empty()
        && (t.chars().all(|c| c.is_ascii_digit())
            || t.chars().all(|c| matches!(c, 'i' | 'v' | 'x' | 'I' | 'V' | 'X')))
}

/// Parse a section spec like "Chorus", "Verse 2", "Pre-Chorus", "Chorus x2",
/// "Part II" -> (lowercased name, repeat count).
fn parse_section_spec(spec: &str) -> Option<(String, u32)> {
    let toks: Vec<&str> = spec.split_whitespace().collect();
    if toks.is_empty() {
        return None;
    }
    let t0 = toks[0].to_lowercase();
    let (name, rest) = if SECTION_KEYWORDS.contains(&t0.as_str()) {
        (t0, &toks[1..])
    } else if toks.len() >= 2
        && matches!(t0.as_str(), "pre" | "post")
        && toks[1].to_lowercase().starts_with("chorus")
    {
        (format!("{t0}-chorus"), &toks[2..])
    } else {
        return None;
    };
    let mut times = 1u32;
    for tok in rest {
        if is_number_token(tok) {
            continue; // section number ("Verse 2", "Part II")
        }
        if let Some(n) = parse_repeat_marker(tok) {
            times = n;
            continue;
        }
        return None;
    }
    Some((name, times))
}

/// Full header-line detection. Returns `(name, times, header_text)`.
/// Handles `[Chorus]`, `(Chorus)`, `{Hook}`, `[Verse 2: Artist]`,
/// `[Chorus x2]`, `[Chorus] (x2)`, and bare `Chorus:` / `Verse 2:` /
/// `Chorus: (x2)` lines.
fn parse_header_line(line: &str) -> Option<(String, u32)> {
    let t = line.trim();
    // bracketed (possibly with a trailing repeat marker outside the brackets)
    if let Some(open) = t.chars().next().filter(|c| matches!(c, '[' | '(' | '{')) {
        let close = match open {
            '[' => ']',
            '(' => ')',
            _ => '}',
        };
        let (_, after) = matching_close(t, open, close)?;
        let inner = &t[open.len_utf8()..after - close.len_utf8()];
        let rest = t[after..].trim();
        let spec = split_off_artist(inner);
        let (name, mut times) = parse_section_spec(spec)?;
        if !rest.is_empty() {
            times = parse_repeat_marker(rest)?; // "[Chorus] (x2)"
        }
        return Some((name, times));
    }
    // bare "Chorus:" / "Verse 2:" — conservative: requires the colon, and
    // anything after it must be a repeat marker (an artist tail on a bare
    // line is left alone; it could be a lyric)
    let (left, right) = t.split_once(':')?;
    let (name, mut times) = parse_section_spec(left)?;
    let right = right.trim();
    if !right.is_empty() {
        times = parse_repeat_marker(right)?;
    }
    Some((name, times))
}

/// "Verse 2: Artist" -> "Verse 2" (also handles " - Artist").
fn split_off_artist(inner: &str) -> &str {
    if let Some((l, _)) = inner.split_once(':') {
        return l;
    }
    if let Some(pos) = inner.find(" - ") {
        return &inner[..pos];
    }
    inner
}

/// Genuinely non-lyric credit / boilerplate lines (stripped, not flagged).
fn is_credit_line(line: &str) -> bool {
    let l = line.trim().to_lowercase();
    const PREFIXES: &[&str] = &[
        "lyrics by ",
        "written by ",
        "produced by ",
        "music by ",
        "words by ",
        "composed by ",
        "arranged by ",
        "mixed by ",
        "mastered by ",
        "performed by ",
        "published by ",
        "courtesy of ",
        "copyright",
        "\u{a9}",  // ©
        "\u{2117}", // ℗
        "(c) ",
        "(p) ",
        "all rights reserved",
        "lyrics licensed",
        "lyrics provided",
        "licensed and provided",
        "source: ",
        "songwriter:",
        "songwriters:",
        "producer:",
        "producers:",
        "writer:",
        "writers:",
        "writer(s):",
        "composer:",
        "composers:",
    ];
    if PREFIXES.iter().any(|p| l.starts_with(p)) {
        return true;
    }
    if l == "you might also like" || l == "embed" {
        return true; // Genius paste junk
    }
    // Genius first line: "23 Contributors…" / "23Contributors…"
    let after_digits = l.trim_start_matches(|c: char| c.is_ascii_digit());
    after_digits.len() < l.len() && after_digits.trim_start().starts_with("contributor")
}

/// Trailing repeat marker on a lyric line: `… (x2)`, `… [x3]`, `… x2`.
/// Returns (kept text, times, marker text as pasted).
fn split_trailing_repeat(line: &str) -> Option<(String, u32, String)> {
    let t = line.trim_end();
    if t.ends_with(')') || t.ends_with(']') {
        let open = if t.ends_with(')') { '(' } else { '[' };
        let start = t.rfind(open)?;
        let marker = &t[start..];
        let times = parse_repeat_marker(marker)?;
        return Some((t[..start].trim_end().to_string(), times, marker.to_string()));
    }
    let last_ws = t.rfind(char::is_whitespace)?;
    let tok = &t[last_ws + 1..];
    let times = parse_repeat_token(tok)?;
    Some((t[..last_ws].trim_end().to_string(), times, tok.to_string()))
}

/// Top-level `( … )` group byte ranges in a line (ad-lib candidates).
fn parenthetical_ranges(s: &str) -> Vec<(usize, usize)> {
    let mut out = Vec::new();
    let mut i = 0usize;
    while i < s.len() {
        if s[i..].starts_with('(') {
            if let Some((_, after)) = matching_close(&s[i..], '(', ')') {
                out.push((i, i + after));
                i += after;
                continue;
            }
            break; // unbalanced: no ad-lib flagging past this point
        }
        i += s[i..].chars().next().map(char::len_utf8).unwrap_or(1);
    }
    out
}

fn tokens_with_spans(s: &str) -> Vec<(usize, usize)> {
    let mut out = Vec::new();
    let mut start: Option<usize> = None;
    for (i, c) in s.char_indices() {
        if c.is_whitespace() {
            if let Some(st) = start.take() {
                out.push((st, i));
            }
        } else if start.is_none() {
            start = Some(i);
        }
    }
    if let Some(st) = start {
        out.push((st, s.len()));
    }
    out
}

